// 문장을 작은따옴표 이름과 나머지 글로 나눈다. 화면에서는 이름만 굵게 보여 준다(따옴표는 빼고).
/**
 * @param {string} text
 * @returns {{ text: string, label: boolean }[]}
 */
export function splitHelpText(text) {
  /** @type {{ text: string, label: boolean }[]} */
  const parts = [];
  let last = 0;
  for (const match of text.matchAll(/'([^']+)'/gu)) {
    if (match.index > last) parts.push({ text: text.slice(last, match.index), label: false });
    parts.push({ text: match[1], label: true });
    last = match.index + match[0].length;
  }
  if (last < text.length) parts.push({ text: text.slice(last), label: false });
  return parts;
}

/** @param {string} text */
export function extractHelpLabels(text) {
  return splitHelpText(text).filter((part) => part.label).map((part) => part.text);
}
